package com.noop.protocol

import com.noop.data.BatteryRow
import com.noop.data.ChargerEdgeRow
import com.noop.data.EventEntry
import com.noop.data.EventRow
import com.noop.data.StreamBatch
import com.noop.data.WhoopDao
import com.noop.data.WhoopRepository
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.lang.reflect.Proxy

/**
 * [ChargerState.resolve] and its store hook. A battery sample with no charging bit takes the state of the
 * latest charger edge at or before it. Twin of Swift `ChargerStateTests` + `ChargerStateStoreTests`.
 */
class ChargerStateTest {
    private val edges = listOf(
        ChargerState.Edge(100, "CHARGING_ON(7)"), ChargerState.Edge(100, "BATTERY_PACK_CONNECTED(21)"),
        ChargerState.Edge(150, "DOUBLE_TAP(14)"),
        ChargerState.Edge(200, "CHARGING_OFF(8)"),
        ChargerState.Edge(300, "CHARGING_ON(7)"),
        ChargerState.Edge(400, "BOOT(15)"),
        ChargerState.Edge(500, "BATTERY_PACK_CONNECTED(21)"),
        ChargerState.Edge(600, "BATTERY_PACK_REMOVED(22)"), ChargerState.Edge(600, "CHARGING_ON(7)"),
    )

    private fun sample(ts: Long, charging: Boolean? = null) = BatteryRow(ts, 50.0, 3900, charging)
    private fun render(v: Boolean?) = v?.let { if (it) "1" else "0" } ?: "nil"

    /** Expected string generated by the Swift twin `ChargerStateTests.testResolveOracle`, pasted verbatim. */
    @Test
    fun resolveOracle() {
        val ts = listOf(50L, 100, 130, 200, 250, 300, 399, 400, 450, 500, 600, 700)
        val resolved = ChargerState.resolve(ts.reversed().map { sample(it) }, edges.reversed())
        assertEquals(
            "50=nil,100=1,130=1,200=0,250=0,300=1,399=1,400=nil,450=nil,500=nil,600=1,700=1",
            resolved.reversed().joinToString(",") { "${it.ts}=${render(it.charging)}" },
        )
    }

    @Test
    fun aFourZeroBitIsKeptAndNoEdgesLeaveNull() {
        val fourZero = listOf(sample(150, false), sample(160, true))
        assertEquals(fourZero, ChargerState.resolve(fourZero, edges))
        assertNull(ChargerState.resolve(listOf(sample(1_000)), emptyList()).single().charging)
        assertNull(ChargerState.resolve(listOf(sample(1_000)), listOf(ChargerState.Edge(1, "WRIST_ON(9)"))).single().charging)
        assertTrue("a later schema name must not read as a boot", !ChargerState.isEdge("BOOTLOADER_ENTERED"))
        assertTrue("a pack attached is not charging", !ChargerState.isEdge("BATTERY_PACK_CONNECTED(21)"))
    }

    @Test
    fun theStoreFilterCoversEveryResolvedKind() {
        for (prefix in ChargerState.kindPrefixes) {
            assertTrue(prefix, WhoopDao.CHARGER_EDGE_FILTER.contains("kind LIKE '$prefix%'"))
        }
    }

    /** Real 5/MG BATTERY_LEVEL frame (the Swift `Whoop5EventTests` fixture): no charging field is decoded. */
    @Test
    fun whoop5BatteryEventDecodesNoChargingBit() {
        val hex = "aa01240001002eb130350300a589266a5118140002f3010000f90e00000000340806003500000000358eb56f"
        val frame = ByteArray(hex.length / 2) { hex.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
        val r = Framing.parseFrame(frame, DeviceFamily.WHOOP5)
        assertEquals("BATTERY_LEVEL(3)", r.parsed["event"])
        assertEquals(49.9, r.parsed["battery_pct"] as Double, 1e-9)
        assertEquals(3833, r.parsed["battery_mV"])
        assertNull(r.parsed["battery_charging"])
    }

    /** An in-memory event/battery store behind the real repository insert path. */
    private class FakeStore {
        val events = mutableListOf<EventRow>()
        val battery = mutableListOf<com.noop.data.BatterySample>()
        val dao: WhoopDao = Proxy.newProxyInstance(
            WhoopDao::class.java.classLoader, arrayOf(WhoopDao::class.java),
        ) { _, method, args ->
            fun edges(pred: (EventRow) -> Boolean) = events
                .filter { pred(it) && ChargerState.kindPrefixes.any { p -> it.kind.startsWith(p) } }
                .map { ChargerEdgeRow(it.ts, it.kind) }
            when (method.name) {
                "insertEvents" -> {
                    @Suppress("UNCHECKED_CAST") val rows = args!![0] as List<EventRow>
                    events += rows; rows.map { 1L }
                }
                "insertBattery" -> {
                    @Suppress("UNCHECKED_CAST") val rows = args!![0] as List<com.noop.data.BatterySample>
                    battery += rows; rows.map { 1L }
                }
                "chargerEdgesBefore" -> edges { it.ts < args!![1] as Long }.sortedByDescending { it.ts }.take(8)
                "chargerEdgesBetween" -> edges { it.ts >= args!![1] as Long && it.ts <= args[2] as Long }
                else -> throw AssertionError("unexpected DAO call ${method.name}")
            }
        } as WhoopDao
    }

    @Test
    fun rowsTakeTheLatestChargerEdgeAcrossBatches() = runBlocking {
        val store = FakeStore()
        val repo = WhoopRepository(store.dao, object : WhoopRepository.Transactor {
            override suspend fun <R> run(block: suspend () -> R): R = block()
        })
        fun ev(ts: Long, kind: String) = EventEntry(ts, kind, "{}")
        suspend fun insert(events: List<EventEntry>, vararg rows: BatteryRow): Boolean? {
            repo.insert(StreamBatch(events = events, battery = rows.toList()), "s")
            return store.battery.last().charging
        }
        assertNull("no edge yet: unknown, not \"not charging\"", insert(emptyList(), BatteryRow(50, 40.0, 3990)))
        assertEquals(true, insert(listOf(ev(100, "BATTERY_PACK_CONNECTED(21)"), ev(100, "CHARGING_ON(7)")),
            BatteryRow(158, 43.2, 3990)))
        assertEquals(true, insert(emptyList(), BatteryRow(188, 43.8, 3990)))
        assertEquals(false, insert(listOf(ev(4_000, "CHARGING_OFF(8)")), BatteryRow(4_030, 97.0, 3990)))
        assertEquals(true, insert(emptyList(), BatteryRow(4_060, 97.0, 3990, charging = true)))
        assertNull(insert(listOf(ev(5_000, "BOOT(15)")), BatteryRow(5_030, 96.0, 3990)))
    }
}
