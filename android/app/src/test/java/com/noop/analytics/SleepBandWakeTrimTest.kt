/**
 * The night ends where the strap's own band says the wearer woke for good
 * ([SleepStager.offsetTrimmedToBandWake]). Kotlin twin of SleepBandWakeTrimTests.swift.
 *
 * [oracleMatchesSwiftTwin] is the parity check: the Swift helper, compiled standalone
 * (`swiftc -O twin.swift main.swift`), staged 300 generated nights; its stdout is pasted below verbatim
 * as `c,start,end,trimmedEnd`. This test regenerates the same nights with the same generator and must
 * reproduce every line.
 */
class SleepBandWakeTrimTest {

    private val d0 = 1_791_936_000L

    private fun band(a: Long, b: Long, state: Int): List<Pair<Long, Int>> = (a until b).map { it to state }
    private fun period(a: Long, b: Long) = SleepStager.Period(stage = "sleep", start = a, end = b)

    @Test
    fun terminalAwakeRunEndsTheNightAtItsFirstSample() {
        val s = d0; val w = d0 + 7 * 3600; val e = w + 50 * 60
        val p = SleepStager.offsetTrimmedToBandWake(period(s, e), band(s, w, 2) + band(w, e + 600, 3))
        assertEquals(s, p.start)
        assertEquals(w, p.end)
    }

    @Test
    fun bandStillAsleepAtTheEndLeavesTheNight() {
        val s = d0; val e = d0 + 8 * 3600
        assertEquals(e, SleepStager.offsetTrimmedToBandWake(period(s, e), band(s, e + 300, 2)).end)
    }

    @Test
    fun awakeningTheBandReturnsFromIsUntouched() {
        val s = d0; val w = d0 + 5 * 3600; val back = w + 20 * 60; val e = d0 + 8 * 3600
        val p = SleepStager.offsetTrimmedToBandWake(period(s, e), band(s, w, 2) + band(w, back, 3) + band(back, e, 2))
        assertEquals(e, p.end)
    }

    @Test
    fun shortTerminalRunIsIgnored() {
        val s = d0; val e = d0 + 8 * 3600; val w = e - (SleepStager.terminalBandWakeMinMin * 60 - 30)
        assertEquals(e, SleepStager.offsetTrimmedToBandWake(period(s, e), band(s, w, 2) + band(w, e, 3)).end)
    }

    @Test
    fun stillBreaksTheAwakeRun() {
        val s = d0; val w = d0 + 7 * 3600; val e = w + 40 * 60
        val p = SleepStager.offsetTrimmedToBandWake(period(s, e),
            band(s, w, 2) + band(w, w + 600, 3) + band(w + 600, w + 660, 1) + band(w + 660, e, 3))
        assertEquals(w + 660, p.end)
    }

    @Test
    fun gapInTheAwakeRunDeclines() {
        val s = d0; val w = d0 + 7 * 3600; val e = w + 40 * 60; val hole = SleepStager.unobservedGapMin * 60L
        assertEquals(e, SleepStager.offsetTrimmedToBandWake(period(s, e),
            band(s, w, 2) + band(w, w + 300, 3) + band(w + 300 + hole, e, 3)).end)
        assertEquals(e, SleepStager.offsetTrimmedToBandWake(period(s, e), band(s, w, 2) + band(w, e - hole, 3)).end)
    }

    @Test
    fun noBandOrAllAwakeBandIsANoOp() {
        val s = d0; val e = d0 + 8 * 3600
        assertEquals(e, SleepStager.offsetTrimmedToBandWake(period(s, e), emptyList()).end)
        assertEquals(e, SleepStager.offsetTrimmedToBandWake(period(s, e), band(s, e, 3)).end)
    }

    // ── parity oracle ────────────────────────────────────────────────────────────────────────────

    private var x: ULong = 0x9E3779B97F4A7C15uL
    private fun next(n: Int): Int {
        x = x * 6364136223846793005uL + 1442695040888963407uL
        return ((x shr 33) % n.toULong()).toInt()
    }

    @Test
    fun oracleMatchesSwiftTwin() {
        val lines = mutableListOf<String>()
        for (c in 0 until 300) {
            val start = 1_800_000_000L + next(86_400)
            val len = 2 * 3600 + next(7 * 3600)
            val end = start + len
            val band = mutableListOf<Pair<Long, Int>>()
            var t = start - next(1800)
            val stopAt = end + next(1800)
            val tailFrom = end - next(90 * 60)
            val tailState = intArrayOf(0, 3, 3, 1, 2)[next(5)]
            while (t < stopAt) {
                var state = 2
                if (t >= tailFrom) state = tailState else if (next(40) == 0) state = next(4)
                if (t >= tailFrom && next(25) == 0) state = next(4)
                val runLen = 1 + next(if (t >= tailFrom) 400 else 1500)
                var u = t
                while (u < t + runLen && u < stopAt) {
                    band.add(u to state)
                    u += if (next(60) == 0) 200 + next(300) else 1 + next(20)
                }
                t = u
            }
            if (next(4) == 0) band.reverse()
            val p = SleepStager.offsetTrimmedToBandWake(period(start, end), band)
            lines.add("$c,$start,$end,${p.end}")
        }
        assertEquals(swiftStdout.trim().lines(), lines)
    }

